export type IconName = keyof typeof icons;

export function Icon({
  name,
  size = 20,
  ...props
}: LucideProps & { name: IconName }) {
  const Glyph = icons[name];
  return <Glyph size={size} strokeWidth={1.8} aria-hidden="true" {...props} />;
}
